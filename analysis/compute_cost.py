"""Inference-cost table (E3) from results/latency.json (scripts/latency.py). Writes paper/tab_cost.tex."""
import json

L = json.load(open("results/latency.json"))
PRETTY = {"protectai-v1": "ProtectAI v1", "protectai-v2": "ProtectAI v2", "protectai-small-v2": "ProtectAI v2-small",
          "jasperls": "JasperLS", "testsavant-large": "TestSavant-L", "piguard": "PIGuard",
          "promptguard1-86m": "Prompt Guard 1", "promptguard2-22m": "Prompt Guard 2 (22M)",
          "promptguard2-86m": "Prompt Guard 2 (86M)", "qualifire-sentinel": "Qualifire Sentinel",
          "rogue-sentinel-v2": "Sentinel v2", "sheltron": "Sheltron", "horizon-base": "Horizon-Labs",
          "wolf-defender": "Wolf Defender", "prismor-1.5b": "Prismor-1.5B",
          "judge-qwen": "Judge (Qwen2.5-7B, 4-bit)", "judge-llama": "Judge (Llama-3.1-8B, 4-bit)"}
NOMINAL = {"judge-qwen": "7.6B", "judge-llama": "8.0B"}  # 4-bit weights are packed, so numel() undercounts


def size(n, k):
    if k in NOMINAL:
        return NOMINAL[k]
    return f"{n / 1e9:.1f}B" if n >= 1e9 else f"{n / 1e6:.0f}M"


rows = sorted([k for k in L if k in PRETTY], key=lambda k: (k.startswith("judge"), L[k]["params"]))
lines = [r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lrrrrrr@{}}", r"\toprule",
         r" & & \multicolumn{3}{c}{GPU (%s)} & \multicolumn{2}{c}{CPU (%d threads)} \\"
         % (L[rows[0]]["gpu_name"].replace("NVIDIA ", ""), L[rows[0]]["cpu_threads"]),
         r"\cmidrule(lr){3-5}\cmidrule(l){6-7}",
         r"Method & Parameters & Median (ms) & p95 (ms) & Memory (MB) & Median (ms) & p95 (ms) \\", r"\midrule"]
for k in rows:
    r = L[k]
    cpu = r.get("cpu")
    if k.startswith("judge") and not any(l.startswith("Judge") for l in lines):
        lines.append(r"\midrule")
    lines.append(f"{PRETTY[k]} & {size(r['params'], k)} & {r['gpu']['median_ms']:.1f} & {r['gpu']['p95_ms']:.1f} & "
                 f"{r['gpu']['peak_mem_mb']:,.0f} & " + (f"{cpu['median_ms']:,.0f} & {cpu['p95_ms']:,.0f}" if cpu else "-- & --")
                 + r" \\")
lines += [r"\bottomrule", r"\end{tabular*}"]
open("paper/tab_cost.tex", "w").write("% generated by analysis/compute_cost.py\n" + "\n".join(lines).replace(",", "{,}") + "\n")
print("\n".join(lines))
print("GPU:", L[rows[0]]["gpu_name"])
