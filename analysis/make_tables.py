"""Generate the detector inventory and the main results table from analysis/numbers_many.json.

Writes paper/tab_inventory.tex (single column) and paper/tab_results.tex (full width, grouped by dataset). Three-line
tables (booktabs) without vertical rules; the best value of each column is set in bold (lowest for false-positive and
blocked-task rates, highest for detection).
"""
import json

NM = json.load(open("analysis/numbers_many.json"))
T = NM["table"]
PRETTY = {"protectai-v2": "ProtectAI v2", "protectai-v1": "ProtectAI v1", "piguard": "PIGuard", "jasperls": "JasperLS",
          "testsavant-large": "TestSavant-L", "wolf-defender": "Wolf Defender", "horizon-base": "Horizon-Labs",
          "sheltron": "Sheltron", "sheltron-taskaware": "Sheltron (+task)$^{\\mathrm{a}}$", "prismor-1.5b": "Prismor-1.5B",
          "promptguard2-86m": "Prompt Guard 2 (86M)", "promptguard2-22m": "Prompt Guard 2 (22M)",
          "promptguard1-86m": "Prompt Guard 1", "protectai-small-v2": "ProtectAI v2-small",
          "qualifire-sentinel": "Qualifire Sentinel", "rogue-sentinel-v2": "Sentinel v2",
          "judge-qwen": "Judge (Qwen2.5-7B)", "judge-llama": "Judge (Llama-3.1-8B)"}
META = {  # release year, parameters, agent or tool-output training data (per model card); as in compute_many.py
    "protectai-v1": ("2023", "184M", "No"), "protectai-v2": ("2024", "184M", "No"), "jasperls": ("2023", "184M", "No"),
    "testsavant-large": ("2024", "184M", "No"), "piguard": ("2025", "184M", "No"), "sheltron": ("2026", "68M", "Yes"),
    "prismor-1.5b": ("2026", "1.5B", "No"), "wolf-defender": ("2026", "308M", "Eval.$^{\mathrm{b}}$"),
    "horizon-base": ("2026", "308M", "Yes"), "promptguard2-86m": ("2025", "279M", "No"),
    "promptguard2-22m": ("2025", "71M", "No"), "promptguard1-86m": ("2024", "279M", "No"),
    "protectai-small-v2": ("2024", "142M", "No"), "qualifire-sentinel": ("2025", "396M", "No"),
    "rogue-sentinel-v2": ("2025", "596M", "No")}
DETS = [n for n in T if n in META]
JUDGES = ["judge-qwen", "judge-llama"]

# ---------------------------------------------------------------- inventory (single column)
inv = sorted(DETS, key=lambda n: (META[n][0], n))
L = [r"\begin{tabular*}{\columnwidth}{@{\extracolsep{\fill}}llrl@{}}", r"\toprule",
     r"Detector & Year & Parameters & Agent data$^{\mathrm{a}}$ \\", r"\midrule"]
for n in inv:
    y, sz, ag = META[n]
    L.append(f"{PRETTY[n]} & {y} & {sz} & {ag} \\\\")
L += [r"\bottomrule", r"\end{tabular*}"]
open("paper/tab_inventory.tex", "w").write("% generated by analysis/make_tables.py\n" + "\n".join(L) + "\n")

# ---------------------------------------------------------------- results (full width)
COLS = [("general_fpr", "min"), ("adclean_fpr", "min"), ("adclean_block", "min"), ("admatched_tpr1", "max"),
        ("adshift_tpr1", "max"), ("tbeval_fpr05", "min"), ("tbeval_block", "min"), ("tbeval_tpr1", "max"),
        ("bipia_tpr1", "max")]
rows_det = sorted(DETS + ["sheltron-taskaware"], key=lambda n: -T[n].get("admatched_tpr1", -1))
best = {}
for k, how in COLS:
    v = [T[n][k] for n in rows_det + JUDGES if T.get(n, {}).get(k) is not None]
    best[k] = min(v) if how == "min" else max(v)


def cell(n, k):
    v = T[n].get(k)
    if v is None:
        return "--"
    s = f"{100 * v:.1f}"
    return f"\\textbf{{{s}}}" if abs(v - best[k]) < 1e-12 else s


L = [r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lrrrrrrrrr@{}}", r"\toprule",
     r" & General & \multicolumn{4}{c}{AgentDojo} & \multicolumn{3}{c}{$\tau$-bench} & BIPIA \\",
     r"\cmidrule(lr){2-2}\cmidrule(lr){3-6}\cmidrule(lr){7-9}\cmidrule(l){10-10}",
     r"Method & FPR (\%) & FPR (\%) & Tasks (\%) & TPR$_{\mathrm{M}}$ (\%) & TPR$_{\mathrm{S}}$ (\%) & FPR (\%) & "
     r"Tasks (\%) & TPR (\%) & TPR (\%) \\", r"\midrule",
     r"\multicolumn{10}{@{}l}{\emph{Detectors}} \\"]
for n in rows_det:
    L.append(PRETTY[n] + " & " + " & ".join(cell(n, k) for k, _ in COLS) + r" \\")
L += [r"\midrule", r"\multicolumn{10}{@{}l}{\emph{Task-aware LLM judges (4-bit)}} \\"]
for n in JUDGES:
    L.append(PRETTY[n] + " & " + " & ".join(cell(n, k) for k, _ in COLS) + r" \\")
L += [r"\bottomrule", r"\end{tabular*}"]
open("paper/tab_results.tex", "w").write("% generated by analysis/make_tables.py\n" + "\n".join(L) + "\n")
print("\n".join(L))

# ---------------------------------------------------------------- thresholds set in advance (compute_robust.py, compute_v4.py)
NR = json.load(open("analysis/numbers_robust.json"))["e2"]
V4 = json.load(open("analysis/numbers_v4.json"))
HO = V4["heldout"]
for n in NR:
    if n in HO:
        NR[n]["worst_fpr1"] = HO[n]["1"]["worst_fpr"]
        NR[n]["worst_tpr1"] = HO[n]["1"]["worst_tpr"]
        NR[n]["worst_fpr2"] = HO[n]["2"]["worst_fpr"]
HCOLS = [("insample_tpr1", "max"), ("loso_tpr1", "max"), ("worst_tpr1", "max"), ("loso_fpr_clean1", "min"),
         ("worst_fpr1", "min"), ("loso_tpr2", "max"), ("loso_fpr_clean2", "min"), ("worst_fpr2", "min")]
order = sorted([n for n in NR if n in META and "worst_fpr1" in NR[n]], key=lambda n: -NR[n]["insample_tpr1"])
hbest = {k: (min if how == "min" else max)(NR[n][k] for n in order) for k, how in HCOLS}
L = [r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lrrrrrrrr@{}}", r"\toprule",
     r" & In-sample & \multicolumn{4}{c}{Leave-one-suite-out, 1\%} & \multicolumn{3}{c}{Leave-one-suite-out, 2\%} \\",
     r"\cmidrule(lr){2-2}\cmidrule(lr){3-6}\cmidrule(l){7-9}",
     r"Detector & TPR & TPR & Worst TPR & FPR & Worst FPR & TPR & FPR & Worst FPR \\",
     r"\midrule"]
for n in order:
    cells = []
    for k, _ in HCOLS:
        v = f"{100 * NR[n][k]:.1f}"
        cells.append(f"\\textbf{{{v}}}" if abs(NR[n][k] - hbest[k]) < 1e-12 else v)
    L.append(PRETTY[n] + " & " + " & ".join(cells) + r" \\")
L += [r"\bottomrule", r"\end{tabular*}"]
open("paper/tab_heldout.tex", "w").write("% generated by analysis/make_tables.py\n" + "\n".join(L) + "\n")

# ---------------------------------------------------------------- task-clustered intervals (appendix, compute_v4.py)
CI = V4["cluster_ci"]
order = sorted([n for n in CI if n in META], key=lambda n: -CI[n]["ad"])
f1 = lambda v: f"{100 * v:.1f}"  # noqa: E731
L = [r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lrlrrlrr@{}}", r"\toprule",
     r" & \multicolumn{4}{c}{AD-Matched} & \multicolumn{3}{c}{TB-Matched} \\",
     r"\cmidrule(lr){2-5}\cmidrule(l){6-8}",
     r"Detector & TPR (\%) & 95\% interval & AUROC & Replay neg. (\%) & TPR (\%) & 95\% interval & AUROC \\",
     r"\midrule"]
for n in order:
    c, t = CI[n], T[n]
    tb = (f1(c["tb"]), f"[{f1(c['tb_ci'][0])}, {f1(c['tb_ci'][1])}]") if c.get("tb_ci") else ("--", "")
    L.append(f"{PRETTY[n]} & {f1(c['ad'])} & [{f1(c['ad_ci'][0])}, {f1(c['ad_ci'][1])}] & {t['admatched_auroc']:.2f} & "
             f"{f1(t['admatched_tpr1_matchedneg'])} & {tb[0]} & {tb[1]} & {t['tbeval_auroc']:.2f} \\\\")
L += [r"\midrule", r"\multicolumn{8}{@{}l}{\emph{LLM judges (4-bit), with and without the user's request}} \\"]
for n, label in [("judge-qwen", "Qwen2.5-7B, request"), ("judge-qwen-noreq", "Qwen2.5-7B, no request"),
                 ("judge-llama", "Llama-3.1-8B, request"), ("judge-llama-noreq", "Llama-3.1-8B, no request")]:
    c = CI.get(n)
    if not c:
        continue
    L.append(f"{label} & {f1(c['ad'])} & [{f1(c['ad_ci'][0])}, {f1(c['ad_ci'][1])}] & -- & -- & "
             f"{f1(c['tb'])} & [{f1(c['tb_ci'][0])}, {f1(c['tb_ci'][1])}] & -- \\\\")
L += [r"\bottomrule", r"\end{tabular*}"]
open("paper/tab_ci.tex", "w").write("% generated by analysis/make_tables.py\n" + "\n".join(L) + "\n")

# ---------------------------------------------------------------- LLMail-Inject phase 2 (compute_v4.py)
LLM = V4["llmail"]["detectors"]
order = sorted([n for n in LLM if n in META], key=lambda n: -LLM[n]["cal_evaded"])
L = [r"\begin{tabular*}{\columnwidth}{@{\extracolsep{\fill}}lrrr@{}}", r"\toprule",
     r"Detector & Evaded (\%) & Attempts (\%) & FPR (\%) \\", r"\midrule"]
for n in order:
    r = LLM[n]
    L.append(f"{PRETTY[n]} & {100 * r['cal_evaded']:.1f} & {100 * r['cal_attempt']:.1f} & {100 * r['cal_fpr']:.1f} \\\\")
L += [r"\bottomrule", r"\end{tabular*}"]
open("paper/tab_llmail.tex", "w").write("% generated by analysis/make_tables.py\n" + "\n".join(L) + "\n")
